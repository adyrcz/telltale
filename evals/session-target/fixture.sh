# Chapter One

The lighthouse had been dark for eleven years, and Nell Okafor had stopped believing it would ever burn again.

She climbed the spiral stairs slowly, her hand trailing the cold iron rail. The air smelled of salt and rust and something older, something like memory.

It wasn't the storm that frightened her. It was the silence after.

At the top, she found her grandfather's logbook open on the desk, the last entry written in his careful hand: *Light the lamp when she comes home.*

Nell's breath caught. In that moment, she understood. Some promises outlive the people who make them.

