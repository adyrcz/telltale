"""Build the `directory` branch: the plugin for the Claude plugin directory.

The directory listing reads the plugin from the root of a branch, and it
accepts only Markdown, text, JSON, YAML, and image files from publishers
that are not Verified organizations. This builds that branch from the
committed `plugin/` folder at HEAD, minus the optional helper script,
which the skill only uses when it is present.

    python3 -I scripts/build_directory.py           # check, then commit to `directory`
    python3 -I scripts/build_directory.py --check   # check only; nothing is committed

Nothing is pushed. Push the branch yourself: git push origin directory
"""

from __future__ import annotations

import io
import os
import re
import subprocess
import sys
import tarfile
import tempfile
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
BRANCH = "directory"
LEFT_OUT = ("skills/telltale/scripts/",)
ALLOWED_SUFFIXES = {".md", ".txt", ".json", ".yaml", ".yml", ".png", ".jpg", ".jpeg", ".gif", ".webp", ".ico"}
ALLOWED_NAMES = {"LICENSE"}
IMAGE_SUFFIXES = {".png", ".jpg", ".jpeg", ".gif", ".webp", ".ico"}
LINK = re.compile(r"\]\(([^)#\s]+)(?:#[^)]*)?\)")


def git(*args: str, env: dict | None = None, data: bytes | None = None) -> str:
    out = subprocess.run(
        ["git", *args], cwd=ROOT, env=env, input=data, capture_output=True, check=False
    )
    if out.returncode != 0:
        sys.exit(f"git {' '.join(args)} failed:\n{out.stderr.decode(errors='replace')}")
    return out.stdout.decode().strip()


def extract(dest: Path) -> None:
    """Write the committed plugin/ tree at HEAD into dest, minus LEFT_OUT."""
    raw = subprocess.run(
        ["git", "archive", "--format=tar", "HEAD", "plugin"], cwd=ROOT, capture_output=True, check=True
    ).stdout
    with tarfile.open(fileobj=io.BytesIO(raw)) as tar:
        for member in tar.getmembers():
            if not member.isfile():
                continue
            rel = member.name[len("plugin/"):]
            if any(rel.startswith(p) for p in LEFT_OUT):
                continue
            out = dest / rel
            out.parent.mkdir(parents=True, exist_ok=True)
            out.write_bytes(tar.extractfile(member).read())


def check(tree: Path) -> list[str]:
    problems = []
    files = sorted(p for p in tree.rglob("*") if p.is_file())
    if not (tree / ".claude-plugin" / "plugin.json").is_file():
        problems.append("no .claude-plugin/plugin.json at the branch root")
    for p in files:
        rel = p.relative_to(tree).as_posix()
        if p.suffix.lower() not in ALLOWED_SUFFIXES and p.name not in ALLOWED_NAMES:
            problems.append(f"{rel}: file type not accepted by the directory")
            continue
        data = p.read_bytes()
        if data.startswith(b"#!"):
            problems.append(f"{rel}: starts with #!")
        if rel.startswith(".claude-plugin/") and p.name != "plugin.json" and p.suffix.lower() not in IMAGE_SUFFIXES:
            problems.append(f"{rel}: only plugin.json and images may sit in .claude-plugin/")
        if p.suffix.lower() in IMAGE_SUFFIXES:
            continue
        if b"\x00" in data:
            problems.append(f"{rel}: contains NUL bytes")
        try:
            text = data.decode("utf-8")
        except UnicodeDecodeError:
            problems.append(f"{rel}: not UTF-8")
            continue
        if p.suffix.lower() == ".md":
            for target in LINK.findall(text):
                if "://" in target or target.startswith("mailto:"):
                    continue
                if not (p.parent / target).exists():
                    problems.append(f"{rel}: link to missing file {target}")
    return problems


def commit(tree: Path) -> str:
    head = git("rev-parse", "--short", "HEAD")
    version = re.search(r'"version":\s*"([^"]+)"', (tree / ".claude-plugin" / "plugin.json").read_text())
    with tempfile.TemporaryDirectory() as tmp:
        env = dict(os.environ, GIT_INDEX_FILE=str(Path(tmp) / "index"))
        git("read-tree", "--empty", env=env)
        git(f"--work-tree={tree}", "add", "-A", "--force", ".", env=env)
        tree_id = git("write-tree", env=env)
    parent = subprocess.run(
        ["git", "rev-parse", "--verify", "--quiet", f"refs/heads/{BRANCH}"], cwd=ROOT, capture_output=True
    ).stdout.decode().strip()
    if parent and git("rev-parse", f"{parent}^{{tree}}") == tree_id:
        return f"{BRANCH} is already up to date ({parent[:7]})"
    msg = f"Directory build of {head} (TellTale {version.group(1) if version else '?'})\n\nGenerated by scripts/build_directory.py from plugin/ on main.\n"
    args = ["commit-tree", tree_id] + (["-p", parent] if parent else [])
    commit_id = git(*args, data=msg.encode())
    git("update-ref", f"refs/heads/{BRANCH}", commit_id)
    return f"{BRANCH} -> {commit_id[:7]} (from {head}). Push with: git push origin {BRANCH}"


def main() -> int:
    only_check = "--check" in sys.argv[1:]
    if not only_check and git("status", "--porcelain", "--", "plugin"):
        print("plugin/ has uncommitted changes; the build uses HEAD, so commit them first.", file=sys.stderr)
        return 1
    with tempfile.TemporaryDirectory() as tmp:
        tree = Path(tmp) / "build"
        tree.mkdir()
        extract(tree)
        problems = check(tree)
        for p in problems:
            print(f"ERROR {p}", file=sys.stderr)
        if problems:
            return 1
        n = sum(1 for p in tree.rglob("*") if p.is_file())
        if only_check:
            print(f"Directory build OK: {n} files, all accepted types.")
            return 0
        print(commit(tree))
    return 0


if __name__ == "__main__":
    sys.exit(main())
